import { Media } from "../types.js";
import { IProvider } from "./Iprovider.js";
import { GoogleGenAI } from "@google/genai";
import { MAX_RECOMMENDATION_CANDIDATES, MAX_RECOMMENDATION_CANDIDATES_PER_TYPE } from "../recommendations.js";

/**
 * GeminiProvider is an implementation of the IProvider interface that leverages Google Gemini AI
 * to generate personalized media recommendations (movies, series, anime, books) based on a user's consumption history.
 * 
 * This provider analyzes the user's history, including media type, completion date, and score, to suggest new titles.
 * It ensures recommendations are relevant, diverse, and not already consumed by the user.
 * 
 * @implements {IProvider}
 * 
 * @example
 * const provider = new GeminiProvider();
 * const recommendations = await provider.recommendation(userMediaHistory);
 */

export class GeminiProvider implements IProvider {

    private ai: GoogleGenAI | null = null;

    private getClient(): GoogleGenAI {
        const apiKey = process.env.GEMINI_API_KEY;
        if (!apiKey) {
            throw new Error('GEMINI_API_KEY is not defined.');
        }

        if (!this.ai) {
            this.ai = new GoogleGenAI({ apiKey });
        }

        return this.ai;
    }

    /**
     * Generates personalized media recommendations based on the user's consumption history.
     *
     * @param media - An array of Media objects representing the user's watched or read items, or null if no history is available.
     * @returns A Promise that resolves to a JSON string containing an array of recommended media items, or null if no response is available.
     *
     * The recommendations are generated by an AI model, following strict rules:
     * - Analyzes user scores and completion dates to infer preferences and recent interests.
     * - Maintains a variety of media types, prioritizing the user's most-watched categories.
     * - Excludes titles already present in the user's history.
     * - Returns results in a specific JSON structure, with a null poster field if unavailable.
     */
    public async recommendation(media: Media[] | null) {

        const userHistory: { name: string, mediaType: string, completeDate: string, score: number }[] = []

        media?.forEach(m => {
            userHistory.push({ name: m.name, mediaType: m.mediaType, completeDate: m.completedDate, score: m.score });
        });

        const response = await this.getClient().models.generateContent({
            model: "gemini-3-flash-preview",
            contents: `Act as an expert movie, series, anime, and book critic and recommendation engine. Your goal is to analyze the user's consumption history and suggest up to ${MAX_RECOMMENDATION_CANDIDATES_PER_TYPE} new titles for each media type (movie, serie, anime, book), for a maximum of ${MAX_RECOMMENDATION_CANDIDATES} titles.

Strict Rules:
1. Analyze the 'score' to understand genres and styles preference.
2. Analyze 'completedDate' to prioritize recent interests.
3. Cover all four 'mediaTypes' (movie, serie, anime, book), with up to ${MAX_RECOMMENDATION_CANDIDATES_PER_TYPE} recommendations per type. Within each type, prioritize genres and styles the user already enjoys.
4. DO NOT recommend titles already present in the user's history.
5. For book recommendations include a valid ISBN-10 or ISBN-13 in 'isbn'. Use null for every other media type.
6. Respond ONLY with a valid JSON array. Do not use markdown or add any text outside the array.

Required JSON Structure:
[
  {
    "name": "Title of the work",
    "mediaType": "movie | serie | anime | book",
    "reason": "A one-sentence explanation of why the user will like it based on their history.",
    "matchPercentage": 95,
    "isbn": "ISBN-10 or ISBN-13 for books, otherwise null"
  }
]
  User History:
  ${JSON.stringify(userHistory)}`,
        });

        return response.text ? response.text : null;
    }

}

